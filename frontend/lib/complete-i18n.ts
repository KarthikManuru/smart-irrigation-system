export function completeTranslate(lang: Lang, text: string): string {
  if (!text) return text;
  const dict = allTranslations[lang] ?? allTranslations.en;
  if (dict && dict[text]) return dict[text];

  const trimmed = text.trim();
  if (dict && dict[trimmed]) return dict[trimmed];

  // Common prefix stripper: handles '✓ ', '• ', '+ ', '! ', '↓ ', '✨ ', '< ', '> '
  const prefixMatch = trimmed.match(/^([✓•+!↓✨<>]\s*)(.*)$/);
  if (prefixMatch) {
    const symbol = prefixMatch[1];
    const inner = prefixMatch[2].trim();
    if (dict && dict[inner]) return `${symbol}${dict[inner]}`;
    if (allTranslations.en?.[inner]) {
      const translatedInner = completeTranslate(lang, inner);
      if (translatedInner !== inner) return `${symbol}${translatedInner}`;
    }
  }

  // Common suffix stripper: handles ' >' or ' >'
  const suffixMatch = trimmed.match(/^(.*?)\s*(&gt;|>)$/);
  if (suffixMatch) {
    const inner = suffixMatch[1].trim();
    const symbol = suffixMatch[2];
    if (dict && dict[inner]) return `${dict[inner]} ${symbol}`;
    const translatedInner = completeTranslate(lang, inner);
    if (translatedInner !== inner) return `${translatedInner} ${symbol}`;
  }

  // Alerts counter pattern: e.g. "3 new alerts"
  const alertCountMatch = trimmed.match(/^(\d+)\s+new alerts$/i);
  if (alertCountMatch) {
    const count = alertCountMatch[1];
    const lbl = dict?.["new alerts"] ?? "new alerts";
    return `${count} ${lbl}`;
  }

  // Variations fallback
  if (trimmed === "Soil Moisture Trend" && dict?.["Soil moisture trend (%)"]) {
    return dict["Soil moisture trend (%)"].replace(/\s*\(\%\)/, "");
  }
  if (trimmed === "Expected increase" && dict?.["Expected increase (sample)"]) {
    return dict["Expected increase (sample)"]
      .replace(/\s*\([^)]*\)/, "")
      .trim();
  }

  // Case-insensitive / prefix fallback for common labels
  if (trimmed.toLowerCase() === "healthy" && (dict?.["Healthy"] ?? dict?.["healthy"])) return dict["Healthy"] ?? dict["healthy"];
  if (trimmed.toLowerCase() === "attention" && (dict?.["Attention"] ?? dict?.["attention"])) return dict["Attention"] ?? dict["attention"];
  if (trimmed.toLowerCase() === "scheduled" && dict?.["Scheduled"]) return dict["Scheduled"];
  if (trimmed.toLowerCase() === "pending" && dict?.["Pending"]) return dict["Pending"];
  if (trimmed.toLowerCase() === "growing" && dict?.["Growing"]) return dict["Growing"];
  if (trimmed.toLowerCase() === "needs attention" && dict?.["Needs Attention"]) return dict["Needs Attention"];
  if (trimmed.toLowerCase() === "planned" && dict?.["Planned"]) return dict["Planned"];
  if (trimmed.toLowerCase() === "view all" && dict?.["View All"]) return dict["View All"];
  if (trimmed.toLowerCase() === "all crops" && dict?.["All Crops"]) return dict["All Crops"];
  if (trimmed.toLowerCase() === "all fields" && dict?.["All Fields"]) return dict["All Fields"];

  // Case-insensitive dictionary search
  if (dict) {
    const lower = trimmed.toLowerCase();
    for (const [k, v] of Object.entries(dict)) {
      if (k.toLowerCase() === lower) return v;
    }
  }

  return allTranslations.en?.[text] ?? text;
}

